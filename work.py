def pick_self_directed_gig() -> dict:
    """Pick a gig Amy can start without any client brief."""
    completed_titles = {i["title"] for i in list_work()}
    options = [g for g in _SELF_DIRECTED_GIGS if g["title"] not in completed_titles]
    if not options:
        # All done — reset so she keeps producing
        return _SELF_DIRECTED_GIGS[int(time.time()) % len(_SELF_DIRECTED_GIGS)]
    return options[int(time.time()) % len(options)]


# --- Internal helpers -------------------------------------------------------

def _log_work(title: str, gig_type: str, path: str, status: str):
    items = []
    if os.path.exists(WORK_LOG):
        with open(WORK_LOG) as f:
            items = json.load(f)
    items.append({
        "title": title,
        "gig_type": gig_type,
        "path": path,
        "status": status,
        "ts": datetime.now().isoformat(),
    })
    with open(WORK_LOG, "w") as f:
        json.dump(items, f, indent=2)


