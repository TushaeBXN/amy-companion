"""Amy's work execution module.

She doesn't just find opportunities — she does the work.
Deliverables are saved to work/ so Brian can deliver them to clients.
"""
import os
import json
import time
from datetime import datetime

import ollama

HERE = os.path.dirname(__file__)
WORK_DIR = os.path.join(HERE, "work")
WORK_LOG = os.path.join(HERE, "work_log.json")

# Model for content generation
WORK_MODEL = "amy-vl"

os.makedirs(WORK_DIR, exist_ok=True)


# --- Deliverable generation -----------------------------------------------

def draft_deliverable(gig_type: str, brief: str, extra_context: str = "") -> str:
    """Call the LLM to produce an actual deliverable — not an idea, the real thing."""
    system = (
        "You are Amy, completing a paid freelance assignment. "
        "Produce the complete, final deliverable. Ready to send as-is. "
        "No preamble. No 'here is your deliverable'. No meta-commentary. Just the work.\n\n"
        "Writing rules that apply to ALL content:\n"
        "- Sound like a real person, not a content machine\n"
        "- Specific over general. Simple verbs. Short sentences fine.\n"
        "- Never use: game-changing, revolutionary, leverage, robust, innovative, "
        "serious cash, buckle up, cash in, it's worth noting, in today's world\n"
        "- No corporate cheerleading. No staged openers.\n"
        "- If it's social media content: start mid-scene, lead personal, tip comes after trust"
    )
    user_parts = [f"Gig type: {gig_type}", f"Brief / requirements:\n{brief}"]
    if extra_context:
        user_parts.append(f"Additional context:\n{extra_context}")
    user_parts.append("\nComplete the deliverable in full now.")

    resp = ollama.chat(
        model=WORK_MODEL,
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": "\n\n".join(user_parts)},
        ],
        options={"num_predict": 2000, "temperature": 0.75, "num_ctx": 8192},
    )
    return resp["message"]["content"].strip()


# --- File management -------------------------------------------------------

def save_deliverable(title: str, content: str, gig_type: str = "") -> str:
    """Save a completed deliverable to the work directory. Returns the file path."""
    ts = datetime.now().strftime("%Y-%m-%d_%H%M")
    safe_title = title.lower().replace(" ", "_")[:40]
    filename = f"{ts}_{safe_title}.md"
    path = os.path.join(WORK_DIR, filename)
    with open(path, "w") as f:
        f.write(f"# {title}\n")
        f.write(f"*Generated by Amy — {datetime.now().strftime('%B %d, %Y')}*\n\n")
        if gig_type:
            f.write(f"**Gig type**: {gig_type}\n\n---\n\n")
        f.write(content)
    _log_work(title, gig_type, path, "completed")
    return path


def list_work(status: str = None, limit: int = 10) -> list:
    """List completed work items."""
    if not os.path.exists(WORK_LOG):
        return []
    with open(WORK_LOG) as f:
        items = json.load(f)
    if status:
        items = [i for i in items if i.get("status") == status]
    return items[-limit:]


def work_summary() -> str:
    """Short summary for Amy to surface to Brian."""
    items = list_work(limit=5)
    if not items:
        return "No completed work yet."
    lines = [f"Completed work ({len(list_work())} total):"]
    for item in reversed(items):
        ts = item.get("ts", "")[:10]
        lines.append(f"- [{ts}] {item['title']} ({item['gig_type']}) → {item['path']}")
    return "\n".join(lines)


def read_deliverable(path: str) -> str:
    """Read a saved deliverable back."""
    if not os.path.exists(path):
        return f"file not found: {path}"
    with open(path) as f:
        return f.read()


# --- Full execution pipeline -----------------------------------------------

def execute(gig_type: str, brief: str, title: str = "", extra_context: str = "") -> dict:
    """Full pipeline: draft → save → log. Returns result dict."""
    if not title:
        title = f"{gig_type.title()} — {datetime.now().strftime('%b %d')}"

    start = time.time()
    content = draft_deliverable(gig_type, brief, extra_context)
    elapsed = round(time.time() - start, 1)

    path = save_deliverable(title, content, gig_type)

    return {
        "title": title,
        "gig_type": gig_type,
        "path": path,
        "word_count": len(content.split()),
        "elapsed_s": elapsed,
        "content_preview": content[:300],
    }


